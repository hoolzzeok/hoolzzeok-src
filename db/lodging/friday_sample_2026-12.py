import statistics as st
# (화 12/1, 금 12/4, 토 12/5)
named={'강릉 세인트존스':(91200,158952,240000),'여수 라마다프라자':(55250,80750,131750),'전주 신라스테이':(81000,141500,202000),
'속초 체스터톤스':(64200,78934,112763),'통영 스탠포드':(132300,163200,223300),'포항 라한':(125000,214500,224000)}
jeonju=[(100000,120000,153000),(56000,107000,164000),(76048,89143,130271),(44000,59000,101000),(58900,68900,125010),(39000,66000,92100),(72000,128700,158400),(113000,150000,170000)]
rows=list(named.values())+jeonju
f=[(b-a)/(c-a) for a,b,c in rows]; fr=[b/a for a,b,c in rows]
for k,(a,b,c) in named.items(): print(f"{k}: 금/화 {b/a:.2f}, 토/화 {c/a:.2f}, 금 위치 {(b-a)/(c-a):.2f}")
print('전주 핀 금/화', [round(b/a,2) for a,b,c in jeonju])
print('n',len(rows),'금/화 중앙값',round(st.median(fr),2),'금 위치(화=0,토=1) 중앙값',round(st.median(f),2),'평균',round(st.mean(f),2))
